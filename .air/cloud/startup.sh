#!/usr/bin/env bash
# Air cloud startup script for the TeamCity Git plugin (Maven multi-module build).
#
# What a task needs to work here:
#  - JDK + Maven + native git (preinstalled in the base image)
#  - ~/.m2/settings.xml with:
#     * the egress proxy (Java/Maven do not read http_proxy/https_proxy env vars)
#     * credentials for https://packages.jetbrains.team/maven/p/tc/maven — the
#       TeamCity snapshot artifacts this build pins (org.jetbrains.teamcity:bom
#       ${MAJOR_VERSION}-SNAPSHOT, oauth-integration-*, custom jgit builds) are
#       only published there, not to the public download.jetbrains.com repo.
#       SPACE_USERNAME / SPACE_PASSWORD come from the environment configuration
#       (personal secrets: your jetbrains.team username and a permanent token
#       with Packages read permission).
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

if [ "${AIR_STARTUP_MODE:-}" = warmup ]; then WARMUP=1; else WARMUP=; fi

log() { echo "[startup] $*"; }

write_maven_settings() {
  local settings="$HOME/.m2/settings.xml"
  local marker="generated-by-air-startup"
  if [ -f "$settings" ] && ! grep -q "$marker" "$settings"; then
    log "keeping existing $settings (not generated by this script)"
    return 0
  fi
  mkdir -p "$HOME/.m2"

  local proxy="${https_proxy:-${HTTPS_PROXY:-${http_proxy:-${HTTP_PROXY:-}}}}"
  local proxies_xml=""
  if [ -n "$proxy" ]; then
    local hostport="${proxy#*://}"
    hostport="${hostport%%/*}"
    local phost="${hostport%%:*}"
    local pport="${hostport##*:}"
    if [ "$pport" = "$phost" ]; then pport=80; fi
    log "configuring Maven proxy $phost:$pport"
    proxies_xml="  <proxies>
    <proxy><id>env-http</id><active>true</active><protocol>http</protocol><host>$phost</host><port>$pport</port><nonProxyHosts>localhost|127.0.0.1</nonProxyHosts></proxy>
    <proxy><id>env-https</id><active>true</active><protocol>https</protocol><host>$phost</host><port>$pport</port><nonProxyHosts>localhost|127.0.0.1</nonProxyHosts></proxy>
  </proxies>"
  fi

  local servers_xml=""
  if [ -n "${SPACE_USERNAME:-}" ] && [ -n "${SPACE_PASSWORD:-}" ]; then
    log "configuring credentials for packages.jetbrains.team (repository id: teamcity-space)"
    servers_xml="  <servers>
    <server><id>teamcity-space</id><username>${SPACE_USERNAME}</username><password>${SPACE_PASSWORD}</password></server>
  </servers>"
  else
    log "WARNING: SPACE_USERNAME / SPACE_PASSWORD are not set — TeamCity snapshot dependencies will not resolve"
  fi

  cat > "$settings" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- $marker: proxy + JetBrains Space Packages access; re-created on every launch -->
<settings>
$proxies_xml
$servers_xml
  <profiles>
    <profile>
      <id>teamcity-space-repo</id>
      <repositories>
        <repository>
          <id>teamcity-space</id>
          <url>https://packages.jetbrains.team/maven/p/tc/maven</url>
          <releases><enabled>true</enabled></releases>
          <snapshots><enabled>true</enabled></snapshots>
        </repository>
      </repositories>
      <pluginRepositories>
        <pluginRepository>
          <id>teamcity-space</id>
          <url>https://packages.jetbrains.team/maven/p/tc/maven</url>
          <releases><enabled>true</enabled></releases>
          <snapshots><enabled>true</enabled></snapshots>
        </pluginRepository>
      </pluginRepositories>
    </profile>
  </profiles>
  <activeProfiles>
    <activeProfile>teamcity-space-repo</activeProfile>
  </activeProfiles>
</settings>
EOF
  chmod 600 "$settings"
}

healthcheck() {
  log "healthcheck: verifying toolchain"
  java -version 2>&1 | head -1
  mvn -version | head -1
  git --version

  log "healthcheck: verifying the plugin zip was built"
  until find "$REPO_DIR" -path '*/target/jetbrains.git.zip' | grep -q .; do
    log "healthcheck: waiting for the plugin zip to appear"
    sleep 10
  done
  log "healthcheck: OK"
}

write_maven_settings

if [ -n "$WARMUP" ]; then
  # Warmup bakes the snapshot real tasks boot from: run the full plugin build so
  # ~/.m2 is primed and every module (including test classes) is compiled.
  log "warmup: running mvn package (builds the plugin zip, primes ~/.m2)"
  cd "$REPO_DIR"
  mvn -B -ntp -U package
  healthcheck
else
  log "task mode: Maven settings refreshed; caches come from the warmup snapshot"
fi
